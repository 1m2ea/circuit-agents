def _node_exe():
    cand = os.path.expanduser("~/.workbuddy/binaries/node/versions/22.22.2/node.exe")
    if os.path.exists(cand):
        return cand
    return shutil.which("node")


def _run_code(exe, path, timeout=60):
    try:
        r = subprocess.run([exe, path], capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout, r.stderr
    except Exception as e:
        return -1, "", str(e)


def codegen_selftest():
    spec = {
        "name": "codegen_demo",
        "components": {
            "src":  {"type": "power", "label": "task"},
            "ret":  {"type": "resistor", "label": "retrieve", "model": "small"},
            "rsn":  {"type": "resistor", "label": "reason", "model": "large"},
            "sum":  {"type": "resistor", "label": "summarize", "model": "small"},
        },
        "wires": [["src", "ret"], ["ret", "rsn"], ["rsn", "sum"]],
    }
    comp = TopologyCompiler()
    allc = comp.emit_all(spec)
    assert set(allc) == {"cpp", "rust", "js"}, "应生成三种语言"
    # 结构校验：三种语言都含拓扑节点 + 主入口 + DONE
    for lang, code in allc.items():
        assert "retrieve" in code and "reason" in code, f"{lang} 应含拓扑节点"
        assert ("int main" in code) or ("fn main" in code) or ("console.log(\"DONE\")" in code), \
            f"{lang} 应含主入口"
    print("✓ 三语言生成：cpp/rust/js 均含拓扑节点 + 主入口")

    # 拓扑序正确性：LAYERS 第一层应为 src，最后一层应为 sum
    import re
    js = allc["js"]
    m = re.search(r"const LAYERS = (\[.*?\]);", js, re.S)
    assert m, "JS 应烘焙 LAYERS"
    assert '"src"' in m.group(1) and '"sum"' in m.group(1), "LAYERS 应含 src/sum"
    print("✓ 拓扑序烘焙：LAYERS 含 src→...→sum 分层")

    # JS 真跑（本机 node）：验证生成代码可运行且数据流正确
    node = _node_exe()
    if node:
        with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as f:
            f.write(js)
            jp = f.name
        rc, out, err = _run_code(node, jp)
        os.unlink(jp)
        assert rc == 0 and "DONE" in out, f"JS 应成功运行并输出 DONE（rc={rc}, err={err}）"
        assert "[sum] summarize" in out, "JS 应打印终端节点 summarize 的执行结果"
        print("✓ JS 真跑（node）：生成代码成功运行，数据流正确（含 [sum] summarize）")
    else:
        print("⚠ JS 未真跑：未找到 node（结构已校验）")

    # C++/Rust：有工具链则真编译运行，否则仅结构校验
    gpp = shutil.which("g++") or shutil.which("clang++")
    if gpp:
        with tempfile.NamedTemporaryFile("w", suffix=".cpp", delete=False, encoding="utf-8") as f:
            f.write(allc["cpp"])
            cp = f.name
        exe = cp + ".bin"
        cr = subprocess.run([gpp, "-O0", "-o", exe, cp], capture_output=True, text=True, timeout=120)
        if cr.returncode == 0:
            rc2 = subprocess.run([exe], capture_output=True, text=True, timeout=30)
            assert rc2.returncode == 0 and "DONE" in rc2.stdout, "C++ 应编译运行成功"
            print("✓ C++ 真编译运行（g++）：生成代码成功编译并执行")
        else:
            print("⚠ C++ 编译失败（工具链异常），仅结构校验通过")
        for p in (cp, exe):
            try: os.unlink(p)
            except OSError: pass
    else:
        assert "int main" in allc["cpp"], "C++ 结构应包含 main"
        print("⚠ C++ 未真编译：未找到 g++（结构已校验）")

    rustc = shutil.which("rustc")
    if rustc:
        with tempfile.NamedTemporaryFile("w", suffix=".rs", delete=False, encoding="utf-8") as f:
            f.write(allc["rust"])
            rp = f.name
        cr = subprocess.run([rustc, "-O", "-o", rp + ".bin", rp],
                            capture_output=True, text=True, timeout=180)
        if cr.returncode == 0:
            rc2 = subprocess.run([rp + ".bin"], capture_output=True, text=True, timeout=30)
            assert rc2.returncode == 0 and "DONE" in rc2.stdout, "Rust 应编译运行成功"
            print("✓ Rust 真编译运行（rustc）：生成代码成功编译并执行")
        else:
            print("⚠ Rust 编译失败（工具链异常），仅结构校验通过")
        for p in (rp, rp + ".bin"):
            try: os.unlink(p)
            except OSError: pass
    else:
        assert "fn main" in allc["rust"], "Rust 结构应包含 main"
        print("⚠ Rust 未真编译：未找到 rustc（结构已校验）")

    # goal 字符串路径：编译后生成
    js2 = comp.emit("查中国GDP总量并预测明年趋势", "js")
    assert "LAYERS" in js2 and "DONE" in js2, "goal 字符串路径应生成可运行 JS"
    print("✓ goal 字符串路径：编译→生成 JS 可运行")

    print("\ncodegen 离线自检全部通过 ✓")


if __name__ == "__main__":
    codegen_selftest()
