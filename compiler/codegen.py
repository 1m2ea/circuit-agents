"""跨语言编译器（Phase 2 ④ 新增）：拓扑 → C++/Rust/JS 可执行代码。

把编译出的电路拓扑（components + wires）翻译成三种目标语言**独立可运行**的源码：
- 每种语言内联一个最小运行时 `run_component(type, label, inputs)`，忠实复现数据流的
  拓扑执行语义（power/source 产出、resistor 变换、capacitor 汇合、opamp 透传、
  adc/verify 校验、tool 技能调用）。
- 拓扑序（Kahn 分层）由 Python 预计算后**烘焙**进生成代码，避免在各语言里重写拓扑排序。
- 零外部依赖：C++/Rust 只用标准库，JS 只用原生。生成即 `g++`/`rustc`/`node` 可跑。

用途：嵌入式端跑 C++、系统/服务跑 Rust、浏览器/Node 跑 JS——同一张电路图三端同源。
"""

import json
import os
import shutil
import tempfile
import subprocess


def _topo(components: dict, wires: list):
    """Kahn 分层 + 前驱表。返回 (layers, preds)。"""
    indeg = {c: 0 for c in components}
    succ = {c: [] for c in components}
    preds = {c: [] for c in components}
    for a, b in wires:
        if a in components and b in components:
            succ[a].append(b)
            preds[b].append(a)
            indeg[b] += 1
    ready = [c for c in components if indeg[c] == 0]
    layers = []
    while ready:
        layers.append(list(ready))
        nxt = []
        for n in ready:
            for m in succ[n]:
                indeg[m] -= 1
                if indeg[m] == 0:
                    nxt.append(m)
        ready = nxt
    # 兜底：若存在环（理论上 compile 已校验无环），把剩余节点单列为最后一层
    rest = [c for c in components if not any(c in L for L in layers)]
    if rest:
        layers.append(rest)
    return layers, preds


class TopologyCompiler:
    """把 spec（或 goal 字符串）编译为 C++/Rust/JS 源码。"""

    LANGS = ("cpp", "rust", "js")

    def __init__(self):
        pass

    # ---- goal/spec 归一 ----
    def _to_spec(self, goal_or_spec):
        if isinstance(goal_or_spec, dict):
            return goal_or_spec
        os.environ.pop("AGENT_API_KEY", None)
        from compiler.compile import compile_goal
        from compiler.nl_parser import GoalParser
        goal = GoalParser().parse(goal_or_spec)
        return compile_goal(goal, auto_bind=True, route=True,
                            memory_enabled=False, auto_select_models=False)

    # ---- 对外入口 ----
    def emit(self, goal_or_spec, language: str):
        language = language.lower()
        if language not in self.LANGS:
            raise ValueError(f"不支持的语言 {language!r}（应为 cpp/rust/js）")
        spec = self._to_spec(goal_or_spec)
        layers, preds = _topo(spec.get("components", {}), spec.get("wires", []))
        if language == "js":
            return self._emit_js(spec, layers, preds)
        if language == "cpp":
            return self._emit_cpp(spec, layers, preds)
        return self._emit_rust(spec, layers, preds)

    def emit_all(self, goal_or_spec):
        return {lang: self.emit(goal_or_spec, lang) for lang in self.LANGS}

    def compile_to_file(self, goal_or_spec, language: str, path: str):
        code = self.emit(goal_or_spec, language)
        with open(path, "w", encoding="utf-8") as f:
            f.write(code)
        return path

    # ---- JS ----
    def _emit_js(self, spec, layers, preds):
        comps = spec.get("components", {})
        L = []
        L.append("// Auto-generated by circuit-agents TopologyCompiler (target: JavaScript)")
        L.append("// Topology: " + json.dumps(spec.get("name", "unnamed")))
        L.append("")
        L.append("function runComponent(type, label, inputs) {")
        L.append('  if (type === "power" || type === "source") return {value: String(label), ok: true, quality: 1.0};')
        L.append('  if (type === "resistor") return {value: label + "(" + inputs.join(" | ") + ")", ok: true, quality: 0.9};')
        L.append('  if (type === "capacitor") return {value: inputs.join(" + "), ok: inputs.length > 0, quality: 0.9};')
        L.append('  if (type === "opamp") return {value: inputs[0] || "", ok: true, quality: 1.0};')
        L.append('  if (type === "adc" || type === "verify") return {value: inputs[0] || "", ok: true, quality: 0.8};')
        L.append('  if (type === "tool") return {value: "tool:" + label, ok: true, quality: 0.95};')
        L.append('  return {value: inputs.join(""), ok: true, quality: 0.8};')
        L.append("}")
        L.append("")
        L.append("const NODES = {")
        for cid, c in comps.items():
            L.append(f'  {json.dumps(cid)}: {{type: {json.dumps(c.get("type", "resistor"))}, label: {json.dumps(c.get("label") or cid)}}},')
        L.append("};")
        L.append("const PREDS = {")
        for cid in comps:
            p = preds.get(cid, [])
            L.append(f'  {json.dumps(cid)}: [{", ".join(json.dumps(x) for x in p)}],')
        L.append("};")
        layers_js = "[" + ", ".join("[" + ", ".join(json.dumps(x) for x in layer) + "]" for layer in layers) + "]"
        L.append(f"const LAYERS = {layers_js};")
        L.append("")
        L.append("const out = {};")
        L.append("for (const layer of LAYERS) {")
        L.append("  for (const id of layer) {")
        L.append("    const ins = (PREDS[id] || []).map(p => out[p].value);")
        L.append("    const s = runComponent(NODES[id].type, NODES[id].label, ins);")
        L.append("    out[id] = s;")
        L.append('    console.log("[" + id + "] " + NODES[id].label + " := " + s.value);')
        L.append("  }")
        L.append("}")
        L.append('console.log("DONE");')
        return "\n".join(L)

    # ---- C++ ----
    def _emit_cpp(self, spec, layers, preds):
        comps = spec.get("components", {})
        q = json.dumps  # 双引号 C++ 字符串字面量合法

        def cpp_str(s):
            return q(s)

        L = []
        L.append("// Auto-generated by circuit-agents TopologyCompiler (target: C++)")
        L.append("#include <iostream>")
        L.append("#include <string>")
        L.append("#include <vector>")
        L.append("#include <map>")
        L.append("")
        L.append("struct Sig { std::string value; bool ok; double quality; };")
        L.append("")
        L.append("Sig runComponent(const std::string& type, const std::string& label, const std::vector<std::string>& inputs) {")
        L.append('  if (type == "power" || type == "source") return {label, true, 1.0};')
        L.append('  if (type == "resistor") { std::string v = label + "("; for (size_t i = 0; i < inputs.size(); ++i) { if (i) v += " | "; v += inputs[i]; } v += ")"; return {v, true, 0.9}; }')
        L.append('  if (type == "capacitor") { std::string v; for (size_t i = 0; i < inputs.size(); ++i) { if (i) v += " + "; v += inputs[i]; } return {v, !inputs.empty(), 0.9}; }')
        L.append('  if (type == "opamp") return {inputs.empty() ? std::string("") : inputs[0], true, 1.0};')
        L.append('  if (type == "adc" || type == "verify") return {inputs.empty() ? std::string("") : inputs[0], true, 0.8};')
        L.append('  if (type == "tool") return {"tool:" + label, true, 0.95};')
        L.append('  std::string v; for (size_t i = 0; i < inputs.size(); ++i) v += inputs[i]; return {v, true, 0.8};')
        L.append("}")
        L.append("")
        L.append("struct Node { std::string type; std::string label; };")
        L.append("")
        L.append("int main() {")
        L.append("  std::map<std::string, Node> NODES;")
        for cid, c in comps.items():
            L.append(f'  NODES[{cpp_str(cid)}] = Node{{{cpp_str(c.get("type", "resistor"))}, {cpp_str(c.get("label") or cid)}}};')
        L.append("  std::map<std::string, std::vector<std::string>> PREDS;")
        for cid in comps:
            p = preds.get(cid, [])
            inner = ", ".join(cpp_str(x) for x in p)
            L.append(f'  PREDS[{cpp_str(cid)}] = {{{inner}}};')
        L.append("  std::vector<std::vector<std::string>> LAYERS = {")
        for layer in layers:
            inner = ", ".join(cpp_str(x) for x in layer)
            L.append(f"    {{{inner}}},")
        L.append("  };")
        L.append("  std::map<std::string, Sig> out;")
        L.append("  for (const auto& layer : LAYERS) {")
        L.append("    for (const auto& id : layer) {")
        L.append("      std::vector<std::string> ins;")
        L.append("      for (const auto& p : PREDS[id]) ins.push_back(out[p].value);")
        L.append("      Sig s = runComponent(NODES[id].type, NODES[id].label, ins);")
        L.append("      out[id] = s;")
        L.append('      std::cout << "[" << id << "] " << NODES[id].label << " := " << s.value << std::endl;')
        L.append("    }")
        L.append("  }")
        L.append('  std::cout << "DONE" << std::endl;')
        L.append("  return 0;")
        L.append("}")
        return "\n".join(L)

    # ---- Rust ----
    def _emit_rust(self, spec, layers, preds):
        comps = spec.get("components", {})
        q = json.dumps

        def rs(s):
            return q(s)

        L = []
        L.append("// Auto-generated by circuit-agents TopologyCompiler (target: Rust)")
        L.append("use std::collections::HashMap;")
        L.append("")
        L.append("struct Sig { value: String, ok: bool, quality: f64 }")
        L.append("")
        L.append("fn run_component(t: &str, label: &str, inputs: &[String]) -> Sig {")
        L.append('    if t == "power" || t == "source" { return Sig { value: label.to_string(), ok: true, quality: 1.0 }; }')
        L.append('    if t == "resistor" { let v = format!("{}({})", label, inputs.join(" | ")); return Sig { value: v, ok: true, quality: 0.9 }; }')
        L.append('    if t == "capacitor" { let v = inputs.join(" + "); return Sig { value: v, ok: !inputs.is_empty(), quality: 0.9 }; }')
        L.append('    if t == "opamp" { let v = inputs.get(0).cloned().unwrap_or_default(); return Sig { value: v, ok: true, quality: 1.0 }; }')
        L.append('    if t == "adc" || t == "verify" { let v = inputs.get(0).cloned().unwrap_or_default(); return Sig { value: v, ok: true, quality: 0.8 }; }')
        L.append('    if t == "tool" { return Sig { value: format!("tool:{}", label), ok: true, quality: 0.95 }; }')
        L.append('    let v = inputs.concat(); return Sig { value: v, ok: true, quality: 0.8 };')
        L.append("}")
        L.append("")
        L.append("fn main() {")
        L.append("    let nodes: HashMap<String, (String, String)> = {")
        L.append("        let mut m = HashMap::new();")
        for cid, c in comps.items():
            L.append(f'        m.insert({rs(cid)}.to_string(), ({rs(c.get("type", "resistor"))}.to_string(), {rs(c.get("label") or cid)}.to_string()));')
        L.append("        m")
        L.append("    };")
        L.append("    let preds: HashMap<String, Vec<String>> = {")
        L.append("        let mut m = HashMap::new();")
        for cid in comps:
            p = preds.get(cid, [])
            inner = ", ".join(f"{rs(x)}.to_string()" for x in p)
            L.append(f'        m.insert({rs(cid)}.to_string(), vec![{inner}]);')
        L.append("        m")
        L.append("    };")
        L.append("    let LAYERS: Vec<Vec<String>> = vec![")
        for layer in layers:
            inner = ", ".join(f"{rs(x)}.to_string()" for x in layer)
            L.append(f"        vec![{inner}],")
        L.append("    ];")
        L.append("    let mut out: HashMap<String, Sig> = HashMap::new();")
        L.append("    for layer in &LAYERS {")
        L.append("        for id in layer {")
        L.append("            let ins: Vec<String> = preds.get(id).unwrap().iter().map(|p| out.get(p).unwrap().value.clone()).collect();")
        L.append("            let n = nodes.get(id).unwrap();")
        L.append("            let s = run_component(&n.0, &n.1, &ins);")
        L.append('            println!("[{}] {} := {}", id, n.1, s.value);')
        L.append("            out.insert(id.clone(), s);")
        L.append("        }")
        L.append("    }")
        L.append('    println!("DONE");')
        L.append("}")
        return "\n".join(L)


